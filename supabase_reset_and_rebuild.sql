-- 5. RLS Policies (PERMISSIVE MODE for Sync)

-- PROFILES
CREATE POLICY "Users can read own profile" ON profiles FOR SELECT USING (auth.uid() = id);
CREATE POLICY "Users can update own profile" ON profiles FOR UPDATE USING (auth.uid() = id);
CREATE POLICY "Users can insert own profile" ON profiles FOR INSERT WITH CHECK (auth.uid() = id);

-- PHARMACIES
CREATE POLICY "Read pharmacy" ON pharmacies FOR SELECT USING (true); -- Public read for login check
CREATE POLICY "Insert pharmacy" ON pharmacies FOR INSERT WITH CHECK (true); -- Allow creation

-- STAFF
-- Allow anyone in the pharmacy to read staff list
CREATE POLICY "Read staff" ON staff FOR SELECT USING (pharmacy_id = get_my_pharmacy_id());
-- Allow admins to manage staff
CREATE POLICY "Admin manage staff" ON staff FOR ALL USING (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
);
-- Allow staff to update themselves (important for sync)
CREATE POLICY "Self update staff" ON staff FOR UPDATE USING (id = auth.uid());
-- Allow staff to insert themselves (important for sync/upsert)
CREATE POLICY "Self insert staff" ON staff FOR INSERT WITH CHECK (id = auth.uid());

-- DATA TABLES (Customers, Suppliers, Inventory, Sales, Shifts)
-- Strategy: Allow INSERT for any authenticated user (to avoid 'new row violates...' on creation)
-- Strategy: Allow SELECT/UPDATE/DELETE only for own pharmacy

-- Customers
CREATE POLICY "Insert customers" ON customers FOR INSERT WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "Manage customers" ON customers FOR ALL USING (pharmacy_id = get_my_pharmacy_id());

-- Suppliers
CREATE POLICY "Insert suppliers" ON suppliers FOR INSERT WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "Manage suppliers" ON suppliers FOR ALL USING (pharmacy_id = get_my_pharmacy_id());

-- Inventory
CREATE POLICY "Insert inventory" ON inventory FOR INSERT WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "Manage inventory" ON inventory FOR ALL USING (pharmacy_id = get_my_pharmacy_id());

-- Sales
CREATE POLICY "Insert sales" ON sales FOR INSERT WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "Manage sales" ON sales FOR ALL USING (pharmacy_id = get_my_pharmacy_id());

-- Shifts
CREATE POLICY "Insert shifts" ON shifts FOR INSERT WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "Manage shifts" ON shifts FOR ALL USING (pharmacy_id = get_my_pharmacy_id());

-- Notifications
CREATE POLICY "Read notifications" ON notifications FOR SELECT USING (pharmacy_id = get_my_pharmacy_id());
CREATE POLICY "Admin insert notifications" ON notifications FOR INSERT WITH CHECK (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
