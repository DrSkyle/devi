-- 10. RPC: Create Pharmacy and Admin Profile (Transactional)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.create_pharmacy_and_admin_profile(
    p_owner_id UUID,
    p_pharmacy_name TEXT,
    p_pharmacy_code TEXT,
    p_pan_number TEXT,
    p_vat_number TEXT,
    p_province TEXT,
    p_district TEXT,
    p_city TEXT,
    p_tole TEXT,
    p_latitude DOUBLE PRECISION,
    p_longitude DOUBLE PRECISION
)
RETURNS SETOF public.profiles
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    new_pharmacy_id BIGINT;
    new_profile_id UUID;
BEGIN
    -- 1. Create Pharmacy
    INSERT INTO public.pharmacies (
        name,
        pharmacy_code,
        pan_number,
        vat_number,
        province,
        district,
        city,
        tole,
        latitude,
        longitude,
        owner_id
    )
    VALUES (
        p_pharmacy_name,
        p_pharmacy_code,
        p_pan_number,
        p_vat_number,
        p_province,
        p_district,
        p_city,
        p_tole,
        p_latitude,
        p_longitude,
        p_owner_id
    )
    RETURNING id INTO new_pharmacy_id;

    -- 2. Create Admin Profile
    INSERT INTO public.profiles (
        id,
        pharmacy_id,
        name,
        role,
        email,
        status
    )
    VALUES (
        p_owner_id,
        new_pharmacy_id,
        'Admin', -- Default name
        'admin',
        (SELECT email FROM auth.users WHERE id = p_owner_id),
        'active'
    )
    RETURNING id INTO new_profile_id;

    -- 3. Return the new profile
    RETURN QUERY SELECT * FROM public.profiles WHERE id = new_profile_id;
END;
$$;

GRANT EXECUTE ON FUNCTION public.create_pharmacy_and_admin_profile TO authenticated;

