-- DDA Logs
CREATE POLICY "Manage dda_logs" ON dda_logs FOR ALL USING (pharmacy_id = get_my_pharmacy_id());

-- App Meta
CREATE POLICY "Public read meta" ON app_meta FOR SELECT USING (true);
CREATE POLICY "Admin manage meta" ON app_meta FOR ALL USING (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
);

